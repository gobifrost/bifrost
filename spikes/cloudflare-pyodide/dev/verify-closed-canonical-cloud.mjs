import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = name => JSON.parse(readFileSync(new URL(name, import.meta.url), 'utf8'));
const build = read('cloud-canonical-build-v1.json');
const local = read('guarded-local-source-v4.json');
assert.equal(build.exit_code, 0);
assert.equal(build.network, 'none');
assert.deepEqual(build.candidate_files_sha256, local.files_sha256);
assert.equal(build.deployment_performed, false);
const cloud = read('closed-canonical-deployment.json');
assert.equal(cloud.worker, 'bifrost-pyodide-spike-ddf316c1');
assert.equal(cloud.workers_dev, false);
assert.equal(cloud.preview_urls, false);
assert.equal(cloud.expiry, '0');
assert.equal(cloud.temporary_auth_in_build, false);
assert.deepEqual(cloud.secrets_after, []);
assert.equal(cloud.deployment_percentage, 100);
assert.equal(cloud.canonical_cloud_execution_verified, false);
assert.equal(cloud.physical_termination_verified, false);
console.log('Accepted candidate build and closed cloud deployment evidence verified; live execution remains unqualified.');
