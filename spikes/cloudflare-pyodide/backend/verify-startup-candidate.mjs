import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../results/startup-candidate/',import.meta.url);
const read=name=>readFileSync(new URL(name,root));
const hash=value=>createHash('sha256').update(value).digest('hex');
const receipt=JSON.parse(read('receipt.json'));
for(const [name,digest] of Object.entries(receipt.artifacts))assert.equal(hash(read(name)),digest);
assert.equal(hash(readFileSync(new URL('prepare-startup-candidate.mjs',import.meta.url))),receipt.preparer_sha256);
assert.equal(hash(readFileSync(new URL('test_startup_candidate.py',import.meta.url))),receipt.test_sha256);
assert.equal(hash(readFileSync(new URL('../../../api/src/worker/remote/remote_pool.py',import.meta.url))),receipt.source_base_sha256);
assert.equal(receipt.shared_source_modified,false);
assert.equal(receipt.live_redis_cleanup_verified,false);
assert.equal(receipt.execution_admission_qualified,false);
assert.equal(receipt.cloud_invocations,0);
assert.match(read('before.txt').toString(),/FAILED \(failures=6, errors=1\)/);
assert.match(read('after.txt').toString(),/Ran 9 tests/);
assert.match(read('expanded.txt').toString(),/Ran 11 tests/);
assert.match(read('before-strict.txt').toString(),/FAILED \(errors=1\)/);
assert.match(read('strict.txt').toString(),/Ran 12 tests/);
for(const name of ['after.txt','expanded.txt','strict.txt','ruff.txt','pyright.txt'])assert.match(read(name).toString(),/exit_code=0/);
console.log('Isolated startup candidate, fail-first lineage and 12 mocked regressions verified; no shared-source application or live cleanup claim.');
