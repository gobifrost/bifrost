import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
const read = name => readFileSync(new URL(name, import.meta.url), 'utf8');
const sha = value => createHash('sha256').update(value).digest('hex');
const tested = name => execFileSync('git', ['show', `025c0806d:spikes/cloudflare-pyodide/backend/${name}`], {encoding: 'utf8'});
const engine = JSON.parse(read('cooperative-budget-v7.json'));
const runtime = JSON.parse(read('rpc-serialization-v14.json'));
assert.equal(engine.qualification_passed, true);
assert.equal(engine.shared_pool_result.oversized_body_failure_verified, true);
assert.equal(engine.shared_pool_result.terminal_obligations_released, true);
assert.equal(engine.packet_sha256['project/backend/cooperative-runtime.mjs'], sha(tested('cooperative-runtime.mjs')));
const staged = `export default ${JSON.stringify(tested('rpc_serialization.py'))};`;
assert.equal(engine.packet_sha256['project/backend/rpc-serialization-code.mjs'], sha(staged));
assert.equal(runtime.packet_sha256['project/backend/rpc-serialization-code.mjs'], sha(staged));
const tests = `export default ${JSON.stringify(tested('test_rpc_serialization.py'))};`;
assert.equal(runtime.packet_sha256['project/backend/rpc-serialization-tests-code.mjs'], sha(tests));
assert.deepEqual([runtime.observation.body.tests_run, runtime.observation.body.failures, runtime.observation.body.errors], [6, 0, 0]);
assert.equal(runtime.observation.body.wire_limit, 4194304);
assert.equal(runtime.observation.body.abi, 'cpython-314-wasm32-emscripten');
assert.equal(runtime.running_after_cleanup, 'false');
assert.deepEqual(engine.running_after_cleanup, []);
assert.equal(engine.cloud_invocations, 0);
assert.equal(runtime.cloud_invocations, 0);
const failed = Object.values(engine.shared_pool_result.attempts).find(item => item.canonical_status === 'Failed');
assert.equal(failed.evidence.provider_outcome.kind, 'terminal_body_too_large');
assert.equal(failed.evidence.provider_outcome.engine_outcome_delivered, false);
assert.equal(failed.evidence.runtime_cleanup.sdk_close_returned, true);
console.log('Pyodide RPC wire-bound tests and actual engine oversized-body handling verified; peak memory remains unqualified.');
